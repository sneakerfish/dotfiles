#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Ollama / ROCm config matrix benchmark for AMD Strix Halo (gfx1151).
#
# Sweeps HSA_OVERRIDE_GFX_VERSION x flash-attention x hipBLASLt, restarting
# ollama for each combination, and measures PREFILL and DECODE separately.
# Prefill is the axis that matters here: native gfx1151 rocBLAS Tensile kernels
# are widely reported as 2.5-6x slower than gfx1100 ones, and that gap is
# invisible to decode-only benchmarks (decode is memory-bandwidth-bound).
#   refs: https://github.com/ROCm/ROCm/issues/4748
#         https://llm-tracker.info/_TOORG/Strix-Halo
#
# This is a moving target -- rerun as ROCm, ollama, and models change.
#
# Usage:
#   sudo ~/bench-ollama-gfx.sh
#   sudo MODEL=qwen3-next:80b-a3b-instruct RUNS=3 ~/bench-ollama-gfx.sh
#   sudo MATRIX=gfx1100-fa,gfx1102-fa ~/bench-ollama-gfx.sh   # subset by label
#
# Env knobs: MODEL RUNS NUM_CTX PROMPT_LINES NUM_PREDICT OLLAMA_URL BIND_HOST
#            OUT MATRIX
#
# Linux/richard-ai only -- drives systemd and ROCm, so it is a no-op on macOS.
# Canonical copy lives in dotfiles/bin; ~/bench-ollama-gfx.sh is a symlink to it.
#
# The original override.conf is restored on exit, including on Ctrl-C.
# ---------------------------------------------------------------------------
set -uo pipefail

MODEL="${MODEL:-qwen3.5:4b}"
RUNS="${RUNS:-3}"
NUM_CTX="${NUM_CTX:-8192}"
PROMPT_LINES="${PROMPT_LINES:-300}"   # ~4.8k prompt tokens
NUM_PREDICT="${NUM_PREDICT:-128}"
OWNER="${SUDO_USER:-$(id -un)}"
OWNER_HOME=$(getent passwd "$OWNER" | cut -d: -f6)

# Endpoints are host-specific and deliberately not in this (public) repo.
# sudo scrubs the environment, so read them from the invoking user's file.
# shellcheck disable=SC1090
[ -f "$OWNER_HOME/.dotfiles.local" ] && source "$OWNER_HOME/.dotfiles.local"

# Client URL the benchmark talks to.
OLLAMA_URL="${OLLAMA_URL:-${OLLAMA_HOST:-}}"
# Server BIND address written into override.conf. Must be a literal address this
# host actually owns -- ollama cannot bind a name it does not own.
BIND_HOST="${BIND_HOST:-${OLLAMA_BIND_HOST:-}}"

if [[ -z $OLLAMA_URL || -z $BIND_HOST ]]; then
  echo "OLLAMA_HOST and OLLAMA_BIND_HOST must be set (see .dotfiles.local.example)," >&2
  echo "either in $OWNER_HOME/.dotfiles.local or as OLLAMA_URL / BIND_HOST in the env." >&2
  exit 1
fi
CONF=/etc/systemd/system/ollama.service.d/override.conf
STAMP=$(date +%Y%m%d-%H%M%S)
OUT="${OUT:-$OWNER_HOME/ollama-gfx-matrix-$STAMP.tsv}"
WARM_TIMEOUT=900       # model load can be slow for large MoE weights
RUN_TIMEOUT=600
CURL_TIMEOUT=$RUN_TIMEOUT

# label | HSA_OVERRIDE_GFX_VERSION (empty = native) | flash_attn | hipblaslt
ALL_MATRIX=(
  "gfx1100|11.0.0|0|0"
  "gfx1102|11.0.2|0|0"
  "native||0|0"
  "gfx1100-fa|11.0.0|1|0"
  "gfx1102-fa|11.0.2|1|0"
  "native-fa||1|0"
  "gfx1100-fa-blaslt|11.0.0|1|1"
  "gfx1102-fa-blaslt|11.0.2|1|1"
  "native-fa-blaslt||1|1"
)

[[ $EUID -eq 0 ]] || { echo "must run as root: sudo $0" >&2; exit 1; }
[[ -f $CONF ]] || { echo "missing $CONF" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq required" >&2; exit 1; }

MATRIX_SEL=()
if [[ -n ${MATRIX:-} ]]; then
  IFS=',' read -ra want <<< "$MATRIX"
  for entry in "${ALL_MATRIX[@]}"; do
    for w in "${want[@]}"; do
      [[ ${entry%%|*} == "$w" ]] && MATRIX_SEL+=("$entry")
    done
  done
  [[ ${#MATRIX_SEL[@]} -gt 0 ]] || { echo "no matrix labels matched: $MATRIX" >&2; exit 1; }
else
  MATRIX_SEL=("${ALL_MATRIX[@]}")
fi

PRISTINE=$(mktemp) || exit 1
cp "$CONF" "$PRISTINE"
restore() {
  trap - EXIT INT TERM
  echo
  echo ">>> restoring original override.conf"
  cp "$PRISTINE" "$CONF"
  systemctl daemon-reload
  systemctl restart ollama
  rm -f "$PRISTINE"
  echo ">>> restored; ollama is $(systemctl is-active ollama)"
}
trap restore EXIT INT TERM

write_conf() {  # $1=hsa  $2=fa  $3=blaslt
  { echo "[Service]"
    echo "# Generated by bench-ollama-gfx.sh at $STAMP -- transient, restored on exit."
    [[ -n $1 ]] && echo "Environment=\"HSA_OVERRIDE_GFX_VERSION=$1\""
    echo "Environment=\"OLLAMA_FLASH_ATTENTION=$2\""
    [[ $3 == 1 ]] && echo "Environment=\"ROCBLAS_USE_HIPBLASLT=1\""
    echo 'Environment="OLLAMA_MAX_VRAM=120000000000"'
    echo 'Environment="OLLAMA_MAX_LOADED_MODELS=3"'
    echo 'Environment="OLLAMA_NUM_PARALLEL=2"'
    echo 'Environment="OLLAMA_KEEP_ALIVE=30m"'
    echo "Environment=\"OLLAMA_HOST=$BIND_HOST\""
    echo
    echo "[Unit]"
    echo "After=tailscaled.service"
    echo "Wants=tailscaled.service"
  } > "$CONF"
}

wait_ready() {
  local deadline=$((SECONDS + 90))
  while (( SECONDS < deadline )); do
    curl -sf --max-time 5 "$OLLAMA_URL/api/tags" >/dev/null 2>&1 && return 0
    sleep 2
  done
  return 1
}

# Nonce-prefixed prompt: ollama caches prompt prefixes, so a repeated identical
# prompt reports a near-zero prefill and would silently invalidate the result.
make_payload() {  # $1=nonce  $2=num_predict
  local filler
  filler=$(yes "The quick brown fox jumps over the lazy dog near the riverbank at dawn." \
           | head -n "$PROMPT_LINES" | tr '\n' ' ')
  jq -nc --arg m "$MODEL" --arg p "run-$1-$STAMP: $filler" \
         --argjson np "$2" --argjson nc "$NUM_CTX" \
    '{model:$m, prompt:$p, stream:false,
      options:{num_predict:$np, temperature:0, num_ctx:$nc}}'
}

# -> "prefill_tps decode_tps prompt_tokens", or non-zero exit on failure
one_run() {  # $1=nonce  $2=num_predict
  make_payload "$1" "$2" \
    | curl -sS --max-time "$CURL_TIMEOUT" "$OLLAMA_URL/api/generate" -d @- 2>/dev/null \
    | python3 -c '
import json,sys
try: d=json.load(sys.stdin)
except Exception: sys.exit(1)
pe,ped=d.get("prompt_eval_count",0),d.get("prompt_eval_duration",0)
e,ed=d.get("eval_count",0),d.get("eval_duration",0)
if not (pe and ped and e and ed): sys.exit(1)
print("%.1f %.2f %d"%(pe/(ped/1e9), e/(ed/1e9), pe))
' 2>/dev/null
}

mean2() {  # stdin: lines of "prefill decode" -> "meanP meanD"
  python3 -c '
import sys
rows=[l.split() for l in sys.stdin if l.strip()]
p=[float(r[0]) for r in rows]; d=[float(r[1]) for r in rows]
print("%.1f %.2f"%(sum(p)/len(p), sum(d)/len(d)))'
}

printf 'label\thsa_override\tflash_attn\thipblaslt\tarch_seen\tprefill_tps\tdecode_tps\tprompt_tokens\tstatus\n' > "$OUT"
chown "$OWNER" "$OUT" 2>/dev/null

echo "model=$MODEL runs=$RUNS num_ctx=$NUM_CTX prompt_lines=$PROMPT_LINES"
echo "configs: ${#MATRIX_SEL[@]}   output: $OUT"

for entry in "${MATRIX_SEL[@]}"; do
  IFS='|' read -r label hsa fa blaslt <<< "$entry"
  echo
  echo "=============================================================="
  echo ">>> $label   HSA=${hsa:-<native>}  FA=$fa  hipBLASLt=$blaslt"

  write_conf "$hsa" "$fa" "$blaslt"
  systemctl daemon-reload
  since=$(date '+%Y-%m-%d %H:%M:%S')
  systemctl restart ollama

  if ! wait_ready; then
    echo "!!! ollama did not come up"
    printf '%s\t%s\t%s\t%s\t-\t-\t-\t-\tSERVICE_DOWN\n' "$label" "${hsa:-native}" "$fa" "$blaslt" >> "$OUT"
    continue
  fi

  echo "--- warmup (loads model; may take a while) ---"
  CURL_TIMEOUT=$WARM_TIMEOUT
  if ! one_run "warm-$label" 8 >/dev/null; then
    echo "!!! warmup failed (crash, OOM, or timeout)"
    journalctl -u ollama --since "$since" --no-pager 2>/dev/null | tail -3
    printf '%s\t%s\t%s\t%s\t-\t-\t-\t-\tWARMUP_FAILED\n' "$label" "${hsa:-native}" "$fa" "$blaslt" >> "$OUT"
    CURL_TIMEOUT=$RUN_TIMEOUT
    continue
  fi
  CURL_TIMEOUT=$RUN_TIMEOUT

  arch=$(journalctl -u ollama --since "$since" --no-pager 2>/dev/null \
         | grep -oE 'compute=gfx[0-9]+' | tail -1 | cut -d= -f2)
  arch=${arch:-unknown}
  echo "--- arch in use: $arch ---"

  samples=$(mktemp); ptok=-; fails=0
  for i in $(seq 1 "$RUNS"); do
    if r=$(one_run "$label-$i" "$NUM_PREDICT"); then
      read -r a b c <<< "$r"
      echo "$a $b" >> "$samples"; ptok=$c
      printf '    run %d: prefill %8s t/s   decode %6s t/s   (%s prompt tok)\n' "$i" "$a" "$b" "$c"
    else
      fails=$((fails+1)); echo "    run $i: FAILED"
    fi
  done

  if [[ ! -s $samples ]]; then
    rm -f "$samples"
    printf '%s\t%s\t%s\t%s\t%s\t-\t-\t-\tALL_RUNS_FAILED\n' "$label" "${hsa:-native}" "$fa" "$blaslt" "$arch" >> "$OUT"
    continue
  fi

  read -r apf adc < <(mean2 < "$samples"); rm -f "$samples"
  status=OK; [[ $fails -gt 0 ]] && status="OK(${fails}_failed)"
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$label" "${hsa:-native}" "$fa" "$blaslt" "$arch" "$apf" "$adc" "$ptok" "$status" >> "$OUT"
  echo ">>> $label mean: prefill $apf t/s   decode $adc t/s"
done

echo
echo "=============================================================="
python3 - "$OUT" <<'PY'
import sys, csv
rows=list(csv.DictReader(open(sys.argv[1]), delimiter='\t'))
ok=[r for r in rows if r['prefill_tps'] not in ('-','')]
w=max([len(r['label']) for r in rows]+[6])
best=max((float(r['prefill_tps']) for r in ok), default=0)
print(f"{'config'.ljust(w)}  {'arch':>8}  {'prefill t/s':>20}  {'decode t/s':>11}  status")
print("-"*(w+56))
for r in sorted(rows, key=lambda r: -float(r['prefill_tps']) if r['prefill_tps'] not in ('-','') else 1):
    p=r['prefill_tps']
    rel=f" ({float(p)/best*100:5.1f}%)" if p not in ('-','') and best else ""
    print(f"{r['label'].ljust(w)}  {r['arch_seen']:>8}  {p:>12}{rel:>8}  {r['decode_tps']:>11}  {r['status']}")
if ok:
    bp=max(ok,key=lambda r: float(r['prefill_tps']))
    bd=max(ok,key=lambda r: float(r['decode_tps']))
    print(f"\nbest prefill: {bp['label']}  {bp['prefill_tps']} t/s  (arch {bp['arch_seen']})")
    print(f"best decode : {bd['label']}  {bd['decode_tps']} t/s  (arch {bd['arch_seen']})")
PY
echo
echo "raw TSV: $OUT"
